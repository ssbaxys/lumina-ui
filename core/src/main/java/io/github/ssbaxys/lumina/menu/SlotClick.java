package io.github.ssbaxys.lumina.menu;

/**
 * Вид щелчка по слоту меню — те же действия, что {@code ClickType} игры: бэкенд передаёт их серверу как есть,
 * а сервер сам проверяет и выполняет (как в ванильных окнах).
 */
public enum SlotClick {
    /** Взять или положить: кнопка 0 — всю стопку, 1 — половину (или положить один предмет). */
    PICKUP,
    /** Shift+клик. */
    QUICK_MOVE,
    /** Обмен с ячейкой хотбара: кнопка — номер ячейки 0..8 или {@link #OFFHAND}. */
    SWAP,
    /** Копия стопки (творческий режим, средняя кнопка). */
    CLONE,
    /** Выбросить из слота: кнопка 0 — один предмет, 1 — всю стопку. */
    THROW,
    /** Раскладка перетаскиванием по нескольким слотам. */
    QUICK_CRAFT,
    /** Собрать такие же предметы (двойной щелчок). */
    PICKUP_ALL;

    /** Номер «слота» щелчка мимо окна: {@link #PICKUP} туда выбрасывает то, что на курсоре. */
    public static final int OUTSIDE = -999;
    /** Кнопка {@link #SWAP} для второй руки (клавиша F). */
    public static final int OFFHAND = 40;
}
